        public static string T(string key, params object[] args)
        {
            var dict = (CurrentLang == "en") ? En : Ru;
            string val;
            if (!dict.TryGetValue(key, out val))
            {
                if (!Ru.TryGetValue(key, out val))
                    val = key;
            }
            if (args != null && args.Length > 0)
            {
                try { return string.Format(val, args); } catch { return val; }
            }
            return val;
        }

        public static Dictionary<string, string> GetDictionary(string lang)
        {
            return (lang == "en") ? new Dictionary<string, string>(En) : new Dictionary<string, string>(Ru);
        }
